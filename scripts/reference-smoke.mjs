import assert from 'node:assert/strict'
import os from 'node:os'
import path from 'node:path'
import { chromium } from 'playwright-core'
import { createServer } from 'vite'

const server = await createServer({ server: { host: '127.0.0.1', port: 4176, strictPort: true } })
let browser
await server.listen()
try {
  browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const tab = name => page.getByRole('tab', { name, exact: true })
  await page.goto('http://127.0.0.1:4176/LogicLab/', { waitUntil: 'networkidle' })
  await page.getByRole('button', { name: '開啟學習路線' }).click()
  await tab('邏輯閘').click()
  assert.equal(await page.locator('.reference-gate-picker button').count(), 8)
  const tables = { AND: [0,0,0,1], OR: [0,1,1,1], NOT: [1,0], NAND: [1,1,1,0], NOR: [1,0,0,0], XOR: [0,1,1,0], XNOR: [1,0,0,1] }
  for (const [type, outputs] of Object.entries(tables)) {
    await page.locator('.reference-gate-picker').getByRole('button', { name: type, exact: true }).click()
    assert.deepEqual(await page.locator('.reference-truth-table tbody tr td:last-child').allTextContents(), outputs.map(String))
  }
  assert.equal(await page.locator('.reference-demo .gate-svg circle').count(), 1)
  await page.getByRole('button', { name: '參考示範：切換 A', exact: true }).click()
  assert.equal(await page.locator('.reference-demo-output strong').innerText(), '0')
  await page.getByRole('button', { name: '參考示範：切換 B', exact: true }).click()
  assert.equal(await page.locator('.reference-demo-output strong').innerText(), '1')
  assert.deepEqual(await page.locator('.reference-truth-table tr.current td').allTextContents(), ['1','1','1'])
  await page.locator('.reference-gate-picker').getByRole('button', { name: 'DFF', exact: true }).click()
  const toggle = name => page.getByRole('button', { name: `參考示範：切換 ${name}`, exact: true }).click()
  const q = async () => page.locator('.reference-demo-output strong').innerText()
  await toggle('D'); assert.equal(await q(), '0')
  await toggle('CLK'); assert.equal(await q(), '1')
  await toggle('D'); assert.equal(await q(), '1')
  await toggle('RST'); assert.equal(await q(), '0')
  await toggle('D'); await toggle('RST'); assert.equal(await q(), '0')
  await toggle('CLK'); assert.equal(await q(), '0')
  await toggle('CLK'); assert.equal(await q(), '1')
  await page.screenshot({ path: path.join(os.tmpdir(), 'logiclab-reference-gates.png') })
  await tab('常見公式').click()
  const search = page.getByRole('searchbox', { name: '搜尋常見公式' })
  await search.fill('全加器')
  assert.equal(await page.locator('.reference-formula-entry').count(), 1)
  assert.match(await page.locator('.reference-formula-entry').innerText(), /CO = AB \+ CI\(A ⊕ B\)/)
  await search.fill('德摩根')
  assert.match(await page.locator('.reference-formula-groups').innerText(), /¬\(AB\) = ¬A \+ ¬B/)
  await page.screenshot({ path: path.join(os.tmpdir(), 'logiclab-reference-formulas.png') })
  await search.fill('xyz-not-a-formula')
  assert.match(await page.locator('.reference-empty').innerText(), /找不到/)
  await tab('常見公式').focus(); await page.keyboard.press('ArrowLeft')
  assert.equal(await tab('邏輯閘').getAttribute('aria-selected'), 'true')
  await page.keyboard.press('ArrowLeft')
  assert.equal(await tab('選擇關卡').getAttribute('aria-selected'), 'true')
  await tab('邏輯閘').click()
  await page.getByRole('button', { name: '關閉選單', exact: true }).focus()
  await page.keyboard.press('Shift+Tab')
  assert.match(await page.locator(':focus').innerText(), /返回首頁/)
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('.route-drawer').count(), 0)
  assert.equal(await page.getByRole('button', { name: '開啟學習路線' }).evaluate(element => element === document.activeElement), true)
  await page.getByRole('button', { name: '開啟學習路線' }).click()
  assert.equal(await tab('邏輯閘').getAttribute('aria-selected'), 'true')
  await tab('選擇關卡').click()
  await page.locator('.drawer-level').filter({ hasText: '接出 AND 閘' }).click()
  await page.getByRole('button', { name: '加入 AND 閘' }).click()
  const gateId = await page.locator('.react-flow__node-gate').getAttribute('data-id')
  const handle = (id, port) => page.locator(`.react-flow__node[data-id="${id}"] .react-flow__handle[data-handleid="${port}"]`)
  await handle('A','out').click(); await handle(gateId,'a').click()
  await page.locator('.react-flow__node-input[data-id="A"] .input-switch').click()
  await page.locator('.primary-test').click()
  const feedback = await page.locator('.test-feedback').innerText()
  const inputBeforeLookup = await page.locator('.react-flow__node-input[data-id="A"] .input-switch').getAttribute('aria-pressed')
  const progress = await page.evaluate(() => localStorage.getItem('logiclab-progress-v1'))
  await page.getByRole('button', { name: '開啟學習路線' }).click()
  await tab('邏輯閘').click()
  await page.getByRole('button', { name: '參考示範：切換 A', exact: true }).click()
  await tab('常見公式').click()
  await page.getByRole('searchbox', { name: '搜尋常見公式' }).fill('選擇器')
  await page.getByRole('button', { name: /返回目前作答/ }).click()
  assert.equal(await page.locator('.react-flow__node-gate').count(), 1)
  assert.equal(await page.locator('.react-flow__edge').count(), 1)
  assert.equal(await page.locator('.react-flow__node-gate').getAttribute('data-id'), gateId)
  assert.equal(await page.locator('.react-flow__node-input[data-id="A"] .input-switch').getAttribute('aria-pressed'), inputBeforeLookup)
  assert.equal(await page.locator('.test-feedback').innerText(), feedback)
  assert.equal(await page.evaluate(() => localStorage.getItem('logiclab-progress-v1')), progress)
  for (const width of [390,320]) {
    const mobile = await browser.newPage({ viewport: { width, height: 844 } })
    mobile.on('pageerror', error => errors.push(error.message))
    await mobile.goto('http://127.0.0.1:4176/LogicLab/', { waitUntil: 'networkidle' })
    await mobile.getByRole('button', { name: '開啟學習路線' }).click()
    await mobile.getByRole('tab', { name: '邏輯閘', exact: true }).click()
    await mobile.locator('.reference-gate-picker').getByRole('button', { name: 'DFF', exact: true }).click()
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    const drawer = await mobile.locator('.route-drawer').boundingBox()
    assert.ok(drawer.x + drawer.width <= width)
    assert.equal(await mobile.locator('.drawer-scroll').evaluate(element => element.scrollWidth <= element.clientWidth), true)
    if (width === 390) await mobile.screenshot({ path: path.join(os.tmpdir(), 'logiclab-reference-mobile.png') })
    await mobile.getByRole('tab', { name: '常見公式', exact: true }).click()
    await mobile.getByRole('searchbox', { name: '搜尋常見公式' }).fill('NAND')
    assert.equal(await mobile.locator('.drawer-scroll').evaluate(element => element.scrollWidth <= element.clientWidth), true)
    await mobile.close()
  }
  assert.deepEqual(errors, [])
  console.log('Reference checks passed: 7 truth tables, DFF edge/reset demo, formula search, keyboard tabs/focus, remembered tab, preserved circuit/feedback/progress and 320/390px layouts.')
} finally {
  await browser?.close()
  await server.close()
}
