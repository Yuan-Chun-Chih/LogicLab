const server = await createServer({ server: { host: '127.0.0.1', port: 4174, strictPort: true } })
await server.listen()
const { checkCircuit } = await server.ssrLoadModule('/src/logic.ts')
const { challenges, wiringGuides } = await server.ssrLoadModule('/src/content.ts')
assert.ok(challenges.filter(challenge => challenge.kind === 'circuit').every(challenge => wiringGuides[challenge.id]?.length >= 3))
const spec = id => challenges.find(challenge => challenge.id === id).circuit
const node = (id, type, gate) => ({ id, type, data: { label: id, gate }, position: { x: 0, y: 0 } })
const edge = (source, target, targetHandle, index) => ({ id: `e${index}`, source, target, targetHandle })
const build = (inputs, outputs, gates, wires) => ({ nodes: [...inputs.map(id => node(id, 'input')), ...outputs.map(id => node(id, 'output')), ...gates.map(([id, gate]) => node(id, gate === 'DFF' ? 'dff' : 'gate', gate === 'DFF' ? undefined : gate))], edges: wires.map((wire, index) => edge(...wire, index)) })

const nandXor = build(['A','B'], ['Y'], [['T','NAND'],['U','NAND'],['V','NAND'],['W','NAND']], [['A','T','a'],['B','T','b'],['A','U','a'],['T','U','b'],['B','V','a'],['T','V','b'],['U','W','a'],['V','W','b'],['W','Y','in']])
assert.equal(checkCircuit(nandXor.nodes, nandXor.edges, spec('sb2')).ok, true)
const half = build(['A','B'], ['S','C'], [['X','XOR'],['G','AND']], [['A','X','a'],['B','X','b'],['X','S','in'],['A','G','a'],['B','G','b'],['G','C','in']])
assert.equal(checkCircuit(half.nodes, half.edges, spec('c3')).ok, true)
const full = build(['A','B','CI'], ['S','C'], [['X1','XOR'],['X2','XOR'],['G1','AND'],['G2','AND'],['O','OR']], [['A','X1','a'],['B','X1','b'],['X1','X2','a'],['CI','X2','b'],['X2','S','in'],['A','G1','a'],['B','G1','b'],['X1','G2','a'],['CI','G2','b'],['G1','O','a'],['G2','O','b'],['O','C','in']])
assert.equal(checkCircuit(full.nodes, full.edges, spec('sb3')).ok, true)
const demorgan = build(['A','B'], ['Y'], [['NA','NOT'],['NB','NOT'],['O','OR']], [['A','NA','a'],['B','NB','a'],['NA','O','a'],['NB','O','b'],['O','Y','in']])
assert.equal(checkCircuit(demorgan.nodes, demorgan.edges, spec('b4')).ok, true)
const parity = build(['A','B','C'], ['Y'], [['X1','XOR'],['X2','XOR']], [['A','X1','a'],['B','X1','b'],['X1','X2','a'],['C','X2','b'],['X2','Y','in']])
assert.equal(checkCircuit(parity.nodes, parity.edges, spec('c5')).ok, true)
const majority = build(['A','B','C'], ['Y'], [['AB','AND'],['AC','AND'],['BC','AND'],['O1','OR'],['O2','OR']], [['A','AB','a'],['B','AB','b'],['A','AC','a'],['C','AC','b'],['B','BC','a'],['C','BC','b'],['AB','O1','a'],['AC','O1','b'],['O1','O2','a'],['BC','O2','b'],['O2','Y','in']])
assert.equal(checkCircuit(majority.nodes, majority.edges, spec('sb4')).ok, true)
const register = build(['D','CLK','RST'], ['Q'], [['F','DFF']], [['D','F','d'],['CLK','F','clk'],['RST','F','rst'],['F','Q','in']])
assert.equal(checkCircuit(register.nodes, register.edges, spec('s4')).ok, true)
const resetFailure = checkCircuit(register.nodes, register.edges.filter(item => item.targetHandle !== 'rst'), spec('s4'))
assert.equal(resetFailure.ok, false)
assert.equal(resetFailure.diagnostic?.output, 'Q')
assert.ok(resetFailure.diagnostic?.step)
const incompleteAnd = build(['A','B'], ['Y'], [['G','AND']], [['A','G','a'],['B','G','b']])
assert.deepEqual(checkCircuit(incompleteAnd.nodes, incompleteAnd.edges, spec('g3')).diagnostic, { inputs: { A: 0, B: 0 }, output: 'Y', expected: 0, actual: 'X' })
const toggle = build(['CLK'], ['Q'], [['F','DFF'],['N','NOT']], [['CLK','F','clk'],['F','N','a'],['N','F','d'],['F','Q','in']])
assert.equal(checkCircuit(toggle.nodes, toggle.edges, spec('s5')).ok, true)

